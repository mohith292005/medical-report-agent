"""Deterministic tool to generate relevant, non-diagnostic questions for the doctor.

Core Principle:
Questions are strictly template-based (NOT generated by an LLM).
They empower the patient with clear, collaborative inquiries for their doctor
without proposing diagnoses or suggesting medication/dosages.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from med_agent.harness.registry import default_registry


class FlaggedItemInput(BaseModel):
    """Input row representing an evaluated test flag."""
    test: str = Field(description="Name of the test")
    flag: str = Field(description="Flag value: LOW, HIGH, NORMAL, NO_RANGE")
    value: Optional[float] = Field(default=None, description="Numeric result value")
    unit: Optional[str] = Field(default=None, description="Measurement unit")


class DoctorQuestionsInput(BaseModel):
    """Input payload for doctor_questions tool."""
    flags: List[FlaggedItemInput] = Field(description="List of flagged test results")


# Question templates categorized by biomarker category
QUESTION_TEMPLATES = {
    "hemoglobin": [
        "What factors might be contributing to my lower hemoglobin level?",
        "Are additional iron studies or vitamin tests recommended to investigate this further?",
        "Should we plan a follow-up complete blood count in a few weeks to monitor this trend?",
    ],
    "wbc": [
        "Could this white blood cell count reflect a recent or ongoing infection, inflammation, or physical stress?",
        "Do you recommend repeating the complete blood count once I am feeling well?",
    ],
    "platelets": [
        "What might be causing this change in my platelet count?",
        "Are there any activities, over-the-counter medications, or precautions I should be mindful of?",
    ],
    "glucose": [
        "What lifestyle or dietary modifications are most appropriate given this blood sugar reading?",
        "Would scheduling an HbA1c test or a repeat fasting test help clarify my overall metabolic health?",
    ],
    "hba1c": [
        "How does this HbA1c reading relate to my average blood sugar over the last few months?",
        "What personalized targets should we set for my blood sugar management?",
    ],
    "creatinine": [
        "Could temporary factors like hydration, exercise, or protein intake have influenced this creatinine result?",
        "Would you recommend checking a repeat kidney panel or urine test in the near future?",
    ],
    "potassium": [
        "Could any of my current medications, supplements, or dietary habits be affecting my potassium levels?",
        "Given the importance of electrolyte balance, how soon should we repeat this test?",
    ],
    "sodium": [
        "Could my fluid intake, sweating, or medications be impacting my sodium balance?",
        "Are there specific symptoms I should watch out for related to this result?",
    ],
    "lipids": [
        "What heart-healthy dietary adjustments or exercise goals would be beneficial based on this lipid profile?",
        "When would you like to re-check my cholesterol and triglyceride levels?",
    ],
    "liver": [
        "Could any medications, supplements, or recent illnesses have irritated my liver enzymes?",
        "Would you advise repeating liver function tests after a short period?",
    ],
    "thyroid": [
        "Do these thyroid test results explain symptoms like changes in energy, weight, or temperature sensitivity?",
        "Would you recommend evaluating free T4 or thyroid antibodies?",
    ],
    "vitamins": [
        "What dietary sources or safe sunshine exposure could help improve these vitamin levels?",
        "Would professional guidance on nutritional supplementation be helpful for me?",
    ],
}

DEFAULT_QUESTIONS = [
    "How do these results compare with my baseline health and previous records?",
    "Are there any specific lifestyle, dietary, or hydration changes you recommend based on this report?",
    "When should I schedule my next follow-up or routine laboratory check-up?",
]


def _match_category(test_name: str) -> Optional[str]:
    """Matches a test name to a template category."""
    t = test_name.lower().strip()
    if any(k in t for k in ("hemoglobin", "haemoglobin", "hb", "hgb", "rbc", "hematocrit", "hct")):
        return "hemoglobin"
    if any(k in t for k in ("wbc", "white blood", "leukocyte")):
        return "wbc"
    if any(k in t for k in ("platelet", "plt")):
        return "platelets"
    if any(k in t for k in ("glucose", "blood sugar", "fbs")):
        return "glucose"
    if any(k in t for k in ("hba1c", "a1c", "glycated")):
        return "hba1c"
    if any(k in t for k in ("creatinine", "bun", "egfr", "urea")):
        return "creatinine"
    if any(k in t for k in ("potassium", "k+")):
        return "potassium"
    if any(k in t for k in ("sodium", "na+")):
        return "sodium"
    if any(k in t for k in ("cholesterol", "ldl", "hdl", "triglyceride", "lipid")):
        return "lipids"
    if any(k in t for k in ("alt", "ast", "sgpt", "sgot", "bilirubin", "alp", "alkaline phosphatase")):
        return "liver"
    if any(k in t for k in ("tsh", "thyroid", "t3", "t4", "ft4")):
        return "thyroid"
    if any(k in t for k in ("vitamin", "vit d", "b12", "ferritin")):
        return "vitamins"
    return None


@default_registry.tool(
    name="doctor_questions",
    description="Generates 3 to 6 generic, non-diagnostic questions for the patient to ask their doctor based on flagged abnormal test results.",
    input_model=DoctorQuestionsInput,
)
def doctor_questions(flags: List[FlaggedItemInput]) -> Dict[str, Any]:
    """Generates 3 to 6 template-based questions for doctor discussion."""
    selected_questions: List[str] = []
    used_categories = set()

    # Prioritize questions for abnormal flags
    abnormal_items = [f for f in flags if f.flag in ("LOW", "HIGH")]

    for item in abnormal_items:
        cat = _match_category(item.test)
        if cat and cat not in used_categories:
            used_categories.add(cat)
            templates = QUESTION_TEMPLATES.get(cat, [])
            for q in templates:
                if q not in selected_questions:
                    selected_questions.append(q)
                    break
        if len(selected_questions) >= 5:
            break

    # If fewer than 3 questions, fill with default questions
    for dq in DEFAULT_QUESTIONS:
        if len(selected_questions) >= 4:
            break
        if dq not in selected_questions:
            selected_questions.append(dq)

    # Ensure between 3 and 6 questions
    final_questions = selected_questions[:6]

    return {
        "questions": final_questions,
        "count": len(final_questions),
    }
